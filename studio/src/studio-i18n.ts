export function studioLocale(value: string | null): StudioLocale {
  return value === 'zh-CN' ? 'zh-CN' : 'en';
}

/** Translate the trusted page source before any API/user content is inserted. */
export function translateStudioTemplate(template: string, locale: StudioLocale): string {
  if (locale === 'zh-CN') return template;
  return template.replace(/[^\x00-\x7f]+(?:[ a-zA-Z0-9/._=-]+[^\x00-\x7f]+)*/g,
    (message) => EN_MESSAGES[message] ?? message);
}
